import { mkdir, readFile, writeFile } from "node:fs/promises";
import { basename } from "node:path";
import { DESIGN_COUNTS, compile, normalizeSource } from "../src/index.js";

const fixtures = [
  new URL("../examples/combinatorial.appblocks", import.meta.url),
  new URL("../examples/showcase.appblocks", import.meta.url),
  new URL("../examples/saas.appblocks", import.meta.url)
];

const rows = [];
for (const url of fixtures) {
  const source = await readFile(url, "utf8");
  const normalized = normalizeSource(source);
  const result = await compile(source, { filename: basename(url.pathname), strict: true });
  rows.push({
    example: basename(url.pathname),
    pages: result.manifest.pages.length,
    blocks: result.manifest.blocks.total,
    sourceBytes: Buffer.byteLength(source),
    sourceEstimatedTokens: Math.ceil(source.length / 4),
    normalizedBytes: Buffer.byteLength(normalized),
    generatedBytes: result.manifest.output.bytes,
    generatedEstimatedTokens: result.manifest.output.estimatedTokens,
    expansionRatio: result.manifest.output.expansionRatio
  });
}

const compact = rows.find((row) => row.example === "combinatorial.appblocks");
if (!compact || compact.expansionRatio < 10) {
  throw new Error(`Compact expansion benchmark failed: ${compact?.expansionRatio ?? "missing"}×`);
}

const integer = new Intl.NumberFormat("en-US");
const report = `# AppBlocks Web 0.2 benchmark\n\nGenerated by \`node scripts/write-v2-benchmark.mjs\`. Byte counts are exact UTF-8 sizes. Token counts are explicitly labelled four-characters-per-token estimates; they are not tokenizer measurements.\n\n| Input | Pages | Blocks | Source bytes | Source est. tokens | Generated bytes | Generated est. tokens | Expansion |\n| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |\n${rows.map((row) => `| \`${row.example}\` | ${row.pages} | ${row.blocks} | ${integer.format(row.sourceBytes)} | ${integer.format(row.sourceEstimatedTokens)} | ${integer.format(row.generatedBytes)} | ${integer.format(row.generatedEstimatedTokens)} | **${row.expansionRatio.toFixed(2)}×** |`).join("\n")}\n\n## Registry breadth\n\n- ${integer.format(DESIGN_COUNTS.recipes)} deterministic complete-site design recipes\n- ${integer.format(DESIGN_COUNTS.virtualBlocks)} deterministic virtual semantic block IDs\n- ${DESIGN_COUNTS.advancedBlocks} advanced semantic block names\n- ${DESIGN_COUNTS.palettes} palettes, ${DESIGN_COUNTS.fonts} font pairings and ${DESIGN_COUNTS.systems} visual systems\n- ${DESIGN_COUNTS.shapes} shape, ${DESIGN_COUNTS.surfaces} surface, ${DESIGN_COUNTS.motions} motion, ${DESIGN_COUNTS.densities} density and ${DESIGN_COUNTS.shadows} shadow axes\n\n## Interpretation\n\nExpansion is not itself a quality score. It shows how much tested browser implementation a model avoids emitting. The compact source still has to provide product-specific routes, content, records and meaningful behavior. The compiler supplies the repeated responsive, accessible and interactive implementation.\n`;

await mkdir(new URL("../benchmarks/", import.meta.url), { recursive: true });
await writeFile(new URL("../benchmarks/v2.json", import.meta.url), `${JSON.stringify({
  format: "appblocks-web-benchmark",
  version: 2,
  generatedAt: new Date().toISOString(),
  design: DESIGN_COUNTS,
  fixtures: rows
}, null, 2)}\n`);
await writeFile(new URL("../docs/BENCHMARK_V2.md", import.meta.url), report);

const readmeUrl = new URL("../README.md", import.meta.url);
let readme = await readFile(readmeUrl, "utf8");
const section = `<!-- V2_BENCHMARK_START -->\n## Version 0.2: combinatorial design engine\n\nAppBlocks now exposes **${integer.format(DESIGN_COUNTS.recipes)} deterministic design recipes**, **${integer.format(DESIGN_COUNTS.virtualBlocks)} virtual semantic block IDs**, ${DESIGN_COUNTS.palettes} palettes, ${DESIGN_COUNTS.fonts} font pairings and ${DESIGN_COUNTS.systems} visual systems without storing thousands of duplicated components. Models may use the compact alias layer while full 0.1 syntax remains compatible.\n\nThe compact showcase expands ${integer.format(compact.sourceEstimatedTokens)} estimated source tokens into ${integer.format(compact.generatedEstimatedTokens)} estimated generated tokens across ${compact.pages} routes and ${compact.blocks} semantic blocks (**${compact.expansionRatio.toFixed(2)}× exact byte expansion**). See [the reproducible 0.2 benchmark](docs/BENCHMARK_V2.md) and [design-engine guide](docs/DESIGN_ENGINE.md).\n<!-- V2_BENCHMARK_END -->`;
const pattern = /<!-- V2_BENCHMARK_START -->[\s\S]*?<!-- V2_BENCHMARK_END -->/;
readme = pattern.test(readme) ? readme.replace(pattern, section) : readme.replace(/\n## Why this exists\n/, `\n\n${section}\n\n## Why this exists\n`);
await writeFile(readmeUrl, readme);

console.table(rows);
console.log(`Wrote docs/BENCHMARK_V2.md and benchmarks/v2.json with ${compact.expansionRatio.toFixed(2)}× compact fixture expansion.`);
